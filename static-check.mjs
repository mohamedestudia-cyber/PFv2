import fs from 'node:fs';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
const root = new URL('../', import.meta.url).pathname;
const read = f => fs.readFileSync(root + f, 'utf8');
for (const f of ['app.js','games-enhanced.js','server.mjs']) execFileSync(process.execPath,['--check',root+f]);
const html=read('index.html'), games=read('games-enhanced.js'), app=read('app.js'), server=read('server.mjs');
for (const id of ['game-menu','game-container','launch-game','game-difficulty','game-history','page-juegos','page-focusia']) assert.equal((html.match(new RegExp(`id=["']${id}["']`,'g'))||[]).length,1,`ID ${id}`);
for (const token of ['Ciutat de l’Atenció','Volcà dels Números','Illes de Paraules','Temple dels Patrons','COMENÇAR LA MISSIÓ','WASD','shift','pointerdown',"e.key.toLowerCase()",'ENTER','pf-pause','pf-exit']) assert.ok(games.includes(token),`game token ${token}`);
for (const token of ['/api/health','/api/focusia','OPENAI_API_KEY','AbortController']) assert.ok(app.includes(token)||server.includes(token),`AI token ${token}`);
assert.ok(read('sw.js').includes('pantalla-focus-v6'),'service worker version');
assert.ok(read('render.yaml').includes('SERVE_FRONTEND\n        value: true'),'Render serves frontend');
const css=read('styles.css');
assert.ok(css.includes('.game-menu{grid-template-columns:1fr'),'mobile game menu collapses to one column');
assert.ok(css.includes('@media(max-width:900px)'),'mobile breakpoint exists');
assert.ok(games.includes('id="pf-sprint"'),'touch sprint control exists');
assert.ok(games.includes("$('#pf-sprint',world).onclick"),'touch sprint handler exists');
assert.ok(games.includes('id="pf-overlay" hidden'),'game overlay starts hidden');
assert.ok(games.includes('function roundRectPath'),'canvas round-rectangle compatibility fallback exists');
assert.ok(games.includes('index++;b.style.opacity=.45;if(index===seq.length)'),'numeric memory allows repeated digits');
console.log('STATIC CHECK PASS');
